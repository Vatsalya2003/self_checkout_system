-- ============================================================================
-- checkout_db -- owned by checkout-service: the sales.
--
-- Open (unpaid) baskets are still memory-only, as since Week 3. A row appears
-- here when the customer pays, and it is written in two steps around the call
-- to inventory-service -- the payment saga:
--
--   tx A  INSERT transactions (status PENDING) + transaction_items (scanned
--         quantities, applied_quantity NULL)       <- "this payment has started"
--   ...   POST inventory /internal/stock/commit    <- the pivot: stock moves
--   tx B  UPDATE applied_quantity, status -> COMPLETED
--
-- A PENDING row is the saga log. If checkout-service dies between the stock
-- commit and tx B, it finds the row on restart and finishes the payment
-- (same transaction id, so inventory answers with what it already did).
-- ============================================================================
DROP TABLE IF EXISTS transaction_items;
DROP TABLE IF EXISTS transactions;

CREATE TABLE transactions (
    id            VARCHAR(64) PRIMARY KEY,      -- a UUID generated by the app
    station_id    VARCHAR(64) NOT NULL,
    status        VARCHAR(16) NOT NULL CHECK (status IN ('PENDING', 'COMPLETED')),
    item_count    INTEGER NOT NULL,             -- units, not distinct SKUs
    running_total NUMERIC(12, 2) NOT NULL,
    started_at    TIMESTAMPTZ NOT NULL,
    completed_at  TIMESTAMPTZ NOT NULL
);

-- Recovery only ever looks for PENDING rows, and there are almost never any,
-- so a partial index keeps that lookup free however many sales there are.
CREATE INDEX transactions_pending ON transactions (id) WHERE status = 'PENDING';

CREATE TABLE transaction_items (
    transaction_id   VARCHAR(64) NOT NULL REFERENCES transactions(id),
    sku              VARCHAR(32) NOT NULL,   -- no FK: items live in catalog_db now
    quantity         INTEGER NOT NULL CHECK (quantity > 0),   -- units SCANNED
    -- units inventory actually took. NULL while the payment is PENDING; set
    -- from inventory's answer in tx B. Smaller than quantity only when the SKU
    -- sold out (the clamp).
    applied_quantity INTEGER,
    PRIMARY KEY (transaction_id, sku)
);
