-- ============================================================================
-- schema.sql -- the whole shared database, rebuilt from scratch by db/reset.sh.
--
-- Week 4: four services share this ONE database, and none of them runs this
-- file (they all use spring.sql.init.mode=never). db/reset.sh is the single
-- owner of the schema; run it, with the services stopped, before every load
-- run. In Weeks 1-3 every boot of the one application rebuilt the database;
-- with four processes that would be four rebuilds racing each other.
--
-- RUN scripts/check-invariant.sql BEFORE resetting if you still care about the
-- results of a load test -- a reset erases them.
-- ============================================================================

-- Drop children before parents, or the foreign keys block the drop.
-- (No DROP ... CASCADE on purpose: cascade would silently take out objects we
-- didn't mean to remove. If a table ever gets renamed, the old one becomes an
-- orphan this script can't see and has to be dropped by hand, once.)
DROP TABLE IF EXISTS popular_snapshots;
DROP TABLE IF EXISTS low_stock_alerts;
DROP TABLE IF EXISTS purchase_log;
DROP TABLE IF EXISTS scan_log;
DROP TABLE IF EXISTS transaction_items;
DROP TABLE IF EXISTS transactions;
DROP TABLE IF EXISTS items;

-- The catalog. This is the only table that holds stock, which is why every
-- stock change has to go through a locked read of one of these rows.
CREATE TABLE items (
    sku   VARCHAR(32) PRIMARY KEY,      -- the SKU string is the key, no surrogate id
    name  VARCHAR(255) NOT NULL,
    price NUMERIC(10, 2) NOT NULL,      -- NUMERIC not FLOAT: exact money, no rounding drift
    stock INTEGER NOT NULL CHECK (stock >= 0)   -- last line of defence: even a bug
                                                -- cannot write negative stock, the
                                                -- INSERT/UPDATE just fails
);

-- One row per customer basket.
CREATE TABLE transactions (
    id            VARCHAR(64) PRIMARY KEY,      -- a UUID generated by the app
    station_id    VARCHAR(64) NOT NULL,
    status        VARCHAR(16) NOT NULL DEFAULT 'OPEN',   -- OPEN / COMPLETED / CANCELLED
    item_count    INTEGER NOT NULL DEFAULT 0,            -- units, not distinct SKUs
    running_total NUMERIC(12, 2) NOT NULL DEFAULT 0,
    started_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at  TIMESTAMPTZ                            -- stays NULL until paid
);

-- The basket lines: which SKUs, how many of each.
CREATE TABLE transaction_items (
    transaction_id VARCHAR(64) NOT NULL REFERENCES transactions(id),
    sku            VARCHAR(32) NOT NULL REFERENCES items(sku),
    quantity       INTEGER NOT NULL DEFAULT 1,   -- units SCANNED (what's on the receipt)
    -- units actually subtracted from stock at completion. Normally equal to
    -- quantity, but smaller when the SKU sold out mid-run and the decrement
    -- was clamped. The stock invariant is checked against THIS column.
    applied_quantity INTEGER NOT NULL DEFAULT 0,
    -- composite key: one line per (basket, SKU) pair, so scanning the same
    -- item twice bumps quantity instead of adding a second row
    PRIMARY KEY (transaction_id, sku)
);

-- One row per SKU, written the moment its stock first crosses below the
-- configured threshold. Stock is never replenished in this simulation, so a
-- SKU crosses at most once and triggered_at is the real crossing time.
CREATE TABLE low_stock_alerts (
    sku          VARCHAR(32) PRIMARY KEY REFERENCES items(sku),   -- PK => at most one alert per SKU
    triggered_at TIMESTAMPTZ NOT NULL
);

-- One row per physical scan, across every station. seq is the global scan
-- counter that the popular-items window slices up.
--
-- Week 4: this table is the HAND-OFF between two services, and it is always
-- written (the old persist-raw-scans switch is gone). checkout-service appends
-- every scan; analytics-service reads them back in seq order to build the
-- popular-items windows. The services never call each other.
--
-- seq is a plain BIGINT ASSIGNED BY checkout-service's single scan-log writer
-- thread, not a BIGSERIAL. It numbers scans as it writes them and commits
-- batches strictly in order, so the committed rows are always exactly 1..K:
-- gapless, which is what lets the window filter test "seq % 500 == 0", and
-- never a later row visible before an earlier one, which is what lets
-- analytics poll "WHERE seq > last ORDER BY seq" safely.
--
-- After a restart the writer continues from MAX(seq), so a restarted
-- checkout-service never collides on this primary key.
CREATE TABLE scan_log (
    seq          BIGINT PRIMARY KEY,
    sku          VARCHAR(32) NOT NULL REFERENCES items(sku),
    scanned_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- One row per computed popular-items window. Append-only, so "the current
-- window" is just the row with the largest id.
CREATE TABLE popular_snapshots (
    id           BIGSERIAL PRIMARY KEY,
    window_start BIGINT NOT NULL,     -- these two are scan seq numbers, NOT timestamps:
    window_end   BIGINT NOT NULL,     -- the window is seq in (window_start, window_end]
    computed_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    items_json   TEXT NOT NULL,       -- the ranked top 10, stored as a JSON array
    -- Exactly one thread produces window boundaries, so two rows with the same
    -- window_end could only mean a bug in the pipeline. The constraint makes
    -- that fail loudly instead of quietly duplicating a window.
    CONSTRAINT popular_snapshots_window_end_key UNIQUE (window_end)
);
